// Extract only platform-independent blocks from the website's source of truth.
// A missing marker fails the build rather than silently shipping stale data.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const source = readFileSync(
  new URL("../../src/riyadh-metro.html", import.meta.url),
  "utf8",
);
function block(start, end) {
  const a = source.indexOf(start),
    b = source.indexOf(end, a + start.length);
  if (a < 0 || b < 0) throw new Error(`Source boundary changed: ${start}`);
  return source.slice(a, b);
}
const blocks = [
  block("const LANGS=[", "function starPts"),
  block("const I18N=", "// ================= DATA"),
  block("const RAW = {", "function renderStatus()"),
  block("const svcById=", "// ================= STATE"),
  block("const state={", "function renderLeave()"),
  block("const endName=", "function setEnd("),
  block("function distM(", "let toastT="),
  block("const CYR=", "const DD_HINT="),
]
  .join("\n")
  .replace(/^function linePath\(.*$/m, "")
  .replace(/^function gmLink\(.*$/m, "")
  .replace(/^const sno=.*$/m, "")
  .replace(/^document.addEventListener\("click",.*a\.gm.*$/m, "");
if (/\b(document|window|navigator|localStorage)\s*\./.test(blocks))
  throw new Error(
    blocks
      .split("\n")
      .filter((l) => /\b(document|window|navigator|localStorage)\s*\./.test(l))
      .join("\n"),
  );
const output = `// GENERATED by scripts/extract-core.mjs; do not edit.\n// source SHA256: ${createHash("sha256").update(source).digest("hex")}\nexport function createMetroEngine() {\n${blocks}\nreturn {
  stations: ST, services: SVC, places: PLACES, languages: LANGS, fares: FARE,
  arabicNames: AR_NAMES, stationNumbers: ST_NO, parkAndRide: PARK_RIDE,
  linePath: ids => lineD(ids),
  setLanguage(code) { if (!I18N[code]) throw new Error('Unknown language'); LANG=code; setNames(); },
  text: t, search: matches, parseToken, nearestStation,
  stationName: id => ST[id]?.n || id,
  name: token => endName(parseToken(token)),
  lineName: id => t(LINES[svcById[id].line].key),
  direction,
  serviceState: (ms=Date.now()) => svcState('metro',cityAt(ms)),
  plan(from,to,departMs=Date.now()) {
    const a=parseToken(from), b=parseToken(to);
    if(!a || !b) throw new Error('Unknown station or place');
    state.departMs=departMs;
    return computeOptions(a,b);
  },
  shareUrl(from,to) {
    if(!parseToken(from)||!parseToken(to)) throw new Error('Unknown station or place');
    return 'https://riyadhmetro.fyi/#'+from+'~'+to+'~'+LANG;
  }
};\n}\n`;
const target = new URL("../src/core/metro.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output)
    throw new Error("Native core is stale; run npm run generate:core");
} else writeFileSync(target, output);
